from typing import Any, Dict


def generate_markdown_report(summary: Dict[str, Any], n_questions: int = 0) -> str:
    modes_data = summary.get("modes", {})

    lines = [
        "# Retrieval & Answer Quality Evaluation Report",
        "",
        f"**Questions evaluated:** {n_questions}",
        "",
        "| Retrieval Mode | hit@5 | MRR | Faithfulness | Citation Accuracy | Refusal Accuracy | Avg Latency (ms) |",
        "|---|---|---|---|---|---|---|",
    ]

    for mode, metrics in modes_data.items():
        hit5 = f"{metrics.get('hit@5', 0.0) * 100:.1f}%"
        mrr = f"{metrics.get('mrr', 0.0):.3f}"
        faith = f"{metrics.get('faithfulness', 0.0) * 100:.1f}%"
        cite = f"{metrics.get('citation_acc', 0.0) * 100:.1f}%"
        refusal = f"{metrics.get('refusal_correct', 0.0) * 100:.1f}%"
        lat = f"{metrics.get('avg_latency_ms', 0)} ms"

        mode_name = mode.replace("_", " ").title()
        lines.append(f"| **{mode_name}** | {hit5} | {mrr} | {faith} | {cite} | {refusal} | {lat} |")

    lines.append("")
    lines.append("> Generated by DocChat Evaluation Harness")
    return "\n".join(lines)
